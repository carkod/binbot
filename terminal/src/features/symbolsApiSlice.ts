import type { StandardResponse } from "../utils/api.types";
import { readApiResponse } from "../utils/api";
import { userApiSlice } from "./userApiSlice";

export interface SymbolRequestPayload {
  id: string;
  symbol?: string;
  // If symbols blacklisted active = false
  active: boolean;
  blacklist_reason: string;
  cooldown?: number;
  cooldown_start_ts?: number;
  futures_leverage: number;
  asset_indices?: number[];
  exchange_id: string;
  base_asset: string;
  description?: string;
  is_margin_trading_allowed?: boolean;
  min_notional?: number;
  price_precision?: number;
  qty_precision?: number;
  quote_asset: string;
}

// From symbol_table.py
export interface ISymbol {
  id: string;
  reason: string;
  created_at: number;
  updated_at: number;
  active: boolean;
  blacklist_reason: string;
  quote_asset: string;
  base_asset: string;
  exchange_id: string;
  price_precision: number;
  qty_precision: number;
  min_qty: number;
  min_notional: number;
  cooldown: number;
  cooldown_start_ts: number;
  futures_leverage: number;
}

export interface GetSymbolsParams {
  market_type?: string;
}

export const symbolsApiSlice = userApiSlice.injectEndpoints({
  endpoints: (build) => ({
    getSymbols: build.query<ISymbol[], GetSymbolsParams | void>({
      query: (params) => {
        const queryParams =
          params && params.market_type
            ? { market_type: params.market_type }
            : undefined;

        return {
          url: `${import.meta.env.VITE_SYMBOLS}`,
          ...(queryParams ? { params: queryParams } : {}),
          providesTags: ["symbols"],
        };
      },
      transformResponse: (response: StandardResponse) =>
        readApiResponse(response),
    }),
    getOneSymbol: build.query<ISymbol, string>({
      query: (pair) => ({
        url: `${import.meta.env.VITE_SYMBOL}/${pair}`,
        providesTags: [
          {
            type: "symbol",
            id: pair,
          },
        ],
      }),
      transformResponse: (response: StandardResponse) =>
        readApiResponse(response),
    }),
    deleteSymbol: build.mutation<void, string>({
      query: (id) => ({
        url: `${import.meta.env.VITE_SYMBOL}/${id}`,
        method: "DELETE",
        invalidatesTags: ["symbols"],
      }),
      transformResponse: (response: StandardResponse) =>
        readApiResponse(response, true),
    }),
    updateSymbol: build.mutation<void, SymbolRequestPayload>({
      query: (body) => ({
        url: `${import.meta.env.VITE_SYMBOL}`,
        method: "PUT",
        body: body,
        invalidatesTags: ["symbols"],
      }),
      transformResponse: (response: StandardResponse) =>
        readApiResponse(response, true),
    }),
  }),
});

// Hooks generated by Redux
export const {
  useGetSymbolsQuery,
  useUpdateSymbolMutation,
  useDeleteSymbolMutation,
  useLazyGetOneSymbolQuery,
} = symbolsApiSlice;
